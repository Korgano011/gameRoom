/// One clue on the board. `level` is how much it gives away: 1 is obscure, 5 practically names the subject.
struct Clue {
    let level: Int
    let text: String
}

/// A secret subject — a famous person, place, thing, tune, musician, movie, TV show, cartoon character or bit of Star Trek — with its 8 clues and 5 look-alike wrong answers.
